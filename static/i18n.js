// ─── CORE HELPERS ─────────────────────────────────────
let currentLang = localStorage.getItem('lang') || 'en';

function t(key) {
  return (TRANSLATIONS[currentLang] && TRANSLATIONS[currentLang][key])
      || (TRANSLATIONS['en'] && TRANSLATIONS['en'][key])
      || key;
}

function tf(key, vars) {
  let str = t(key);
  for (const [k, v] of Object.entries(vars)) {
    str = str.replace(`{${k}}`, v);
  }
  return str;
}

function setLanguage(lang) {
  currentLang = lang;
  localStorage.setItem('lang', lang);
  applyTranslations();
}

function applyTranslations() {
  // Static text content
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = t(el.dataset.i18n);
  });
  // Placeholder attributes
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = t(el.dataset.i18nPlaceholder);
  });
  // Title attributes
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.dataset.i18nTitle);
  });
  // Sync language selector
  const sel = document.getElementById('lang-select');
  if (sel) sel.value = currentLang;
  // Dynamic elements that depend on app state
  const resultsVisible = document.getElementById('section-results') &&
                         document.getElementById('section-results').style.display !== 'none';
  const isSeries = typeof currentMediaType !== 'undefined' && currentMediaType === 'series';
  const totalLabel = document.getElementById('stat-total-label');
  if (totalLabel) {
    totalLabel.textContent = resultsVisible
      ? t(isSeries ? 'stat_total_episodes' : 'stat_total_movies')
      : t('stat_total_items');
  }
}